#!/usr/bin/env bash

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export XDG_STATE_HOME="${XDG_STATE_HOME:-$HOME/.tuist_state}"
TVOS_WORKSPACE="$ROOT_DIR/tvosApp/NuvioTV.xcworkspace"
TVOS_SCHEME="NuvioTV"
OUTPUT_DIR="${NUVIO_IPA_OUTPUT_DIR:-$ROOT_DIR/build-ipa}"
ARCHIVE_DIR="$(mktemp -d)/NuvioTV.xcarchive"

cleanup() {
  rm -rf "$(dirname "$ARCHIVE_DIR")"
}
trap cleanup EXIT

if [[ ! -f "$ROOT_DIR/MPVKit/Package.swift" ]]; then
  echo "==> Initializing git submodules (MPVKit)..."
  git -C "$ROOT_DIR" submodule update --init --recursive
fi

# The Xcode project is generated by Tuist and is not tracked in git.
echo "==> Generating Xcode project with Tuist..."
if command -v tuist >/dev/null 2>&1; then
  (cd "$ROOT_DIR/tvosApp" && tuist generate --no-open)
elif command -v mise >/dev/null 2>&1; then
  (cd "$ROOT_DIR/tvosApp" && mise exec -- tuist generate --no-open)
else
  echo "error: tuist not found. Install it with 'mise install' (see mise.toml)." >&2
  exit 1
fi

echo "==> Archiving ${TVOS_SCHEME} for tvOS (Release, unsigned)..."
xcodebuild archive \
  -workspace "$TVOS_WORKSPACE" \
  -scheme "$TVOS_SCHEME" \
  -configuration Release \
  -destination 'generic/platform=tvOS' \
  -archivePath "$ARCHIVE_DIR" \
  CODE_SIGN_IDENTITY="" \
  CODE_SIGNING_REQUIRED=NO \
  CODE_SIGNING_ALLOWED=NO \
  CODE_SIGN_ENTITLEMENTS="" \
  -quiet

APP_PATH="$ARCHIVE_DIR/Products/Applications/NuvioTV.app"
if [[ ! -d "$APP_PATH" ]]; then
  echo "Error: Archive failed, NuvioTV.app not found at $APP_PATH" >&2
  exit 1
fi

# Bundled deploy ids. Info.plist declares them as placeholders that Xcode
# substitutes from build settings, but Tuist caches its manifest evaluation, so
# a cached project generated before the settings existed bakes them out as
# empty strings and the app ships with no bundled app at all. Fill them here,
# after the archive, from this run's environment. Unset stays empty, which is
# what a local build should ship.
if [[ -n "${TRAKT_CLIENT_ID:-}" ]]; then
  if ! /usr/libexec/PlistBuddy -c "Set :TraktClientID ${TRAKT_CLIENT_ID}" "$APP_PATH/Info.plist" 2>/dev/null; then
    /usr/libexec/PlistBuddy -c "Add :TraktClientID string ${TRAKT_CLIENT_ID}" "$APP_PATH/Info.plist"
  fi
  echo "==> Bundled Trakt client id"
fi
if [[ -n "${TMDB_API_KEY:-}" ]]; then
  if ! /usr/libexec/PlistBuddy -c "Set :TmdbApiKey ${TMDB_API_KEY}" "$APP_PATH/Info.plist" 2>/dev/null; then
    /usr/libexec/PlistBuddy -c "Add :TmdbApiKey string ${TMDB_API_KEY}" "$APP_PATH/Info.plist"
  fi
  echo "==> Bundled TMDB key"
fi

# Build stamp. Sideloading keeps the bundle id and version identical between
# runs, so the device cannot otherwise tell a new IPA from an old one. The CI
# passes the tag and commit; Settings → About shows it, which makes "am I
# running the new build?" a question the screen answers.
if [[ -n "${BOOMIO_BUILD_STAMP:-}" ]]; then
  if ! /usr/libexec/PlistBuddy -c "Set :BoomioBuildStamp ${BOOMIO_BUILD_STAMP}" "$APP_PATH/Info.plist" 2>/dev/null; then
    /usr/libexec/PlistBuddy -c "Add :BoomioBuildStamp string ${BOOMIO_BUILD_STAMP}" "$APP_PATH/Info.plist"
  fi
  echo "==> Build stamp ${BOOMIO_BUILD_STAMP}"
fi

VERSION=$(/usr/libexec/PlistBuddy -c "Print :CFBundleShortVersionString" "$APP_PATH/Info.plist" 2>/dev/null || echo "latest")

echo "==> Packaging unsigned IPA for version ${VERSION}..."
rm -rf "$OUTPUT_DIR/Payload" "$OUTPUT_DIR"/*.ipa
mkdir -p "$OUTPUT_DIR/Payload"
cp -R "$APP_PATH" "$OUTPUT_DIR/Payload/"

# The archive is built without entitlements, so a sideloader re-signing the IPA
# finds no App Group to register, and the Top Shelf extension never sees the
# rows the app writes (the shelf shows only the app's name). Pseudo-sign the
# app and its extensions with just the App Group from TopShelf.entitlements;
# sideloaders read it when they re-sign. The other entitlements stay out, as a
# free developer account can't provide them.
APP_GROUP=$(/usr/libexec/PlistBuddy -c "Print :com.apple.security.application-groups:0" \
  "$ROOT_DIR/tvosApp/TopShelf/TopShelf.entitlements" 2>/dev/null || true)
if [[ -z "$APP_GROUP" ]]; then
  echo "warning: no App Group in TopShelf.entitlements; the Top Shelf will stay empty after sideloading." >&2
else
  if command -v ldid >/dev/null 2>&1; then
    SIGNING_METHOD="ldid"
  elif command -v codesign >/dev/null 2>&1; then
    # Apple's ad-hoc CodeDirectory also carries an entitlement blob that
    # sideloaders can read before they re-sign the app for the target device.
    SIGNING_METHOD="codesign"
  else
    SIGNING_METHOD=""
    echo "warning: neither ldid nor codesign is available; the IPA has no App Group, so the Top Shelf will stay empty after sideloading." >&2
  fi

  if [[ -n "$SIGNING_METHOD" ]]; then
    echo "==> Embedding App Group ${APP_GROUP} (Top Shelf) via ${SIGNING_METHOD}..."
    GROUP_ENTITLEMENTS="$(dirname "$ARCHIVE_DIR")/app-group.entitlements"
    cat > "$GROUP_ENTITLEMENTS" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>com.apple.security.application-groups</key>
	<array>
		<string>${APP_GROUP}</string>
	</array>
</dict>
</plist>
PLIST
    PAYLOAD_APP="$OUTPUT_DIR/Payload/NuvioTV.app"
    # Extensions first: signing the app seals what it contains.
    for BUNDLE in "$PAYLOAD_APP"/PlugIns/*.appex "$PAYLOAD_APP"; do
      [[ -d "$BUNDLE" ]] || continue
      EXECUTABLE=$(/usr/libexec/PlistBuddy -c "Print :CFBundleExecutable" "$BUNDLE/Info.plist")
      if [[ "$SIGNING_METHOD" == "ldid" ]]; then
        ldid -S"$GROUP_ENTITLEMENTS" "$BUNDLE/$EXECUTABLE"
      else
        codesign --force --sign - --entitlements "$GROUP_ENTITLEMENTS" "$BUNDLE/$EXECUTABLE"
      fi
    done
  fi
fi

(
  cd "$OUTPUT_DIR"
  zip -qry "BoomioTV-unsigned.ipa" Payload
  cp "BoomioTV-unsigned.ipa" "BoomioTV-${VERSION}-unsigned-release.ipa"
)

echo "==> Unsigned IPA created successfully:"
ls -lh "$OUTPUT_DIR"/*.ipa
